const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const sandbox={window:{},console};
vm.runInNewContext(fs.readFileSync('web/family.js','utf8'),sandbox);
const render=sandbox.window.TeacherFamily.render;
const base={role:'parent',mode:'demo',loggedIn:true,classroom:{id:'class-a',name:'Room 204',share_grades:true,allow_parent_replies:true},students:[{id:'student-a',display_name:'Student A'},{id:'student-b',display_name:'Student B'}],guardianIds:['student-a'],links:[],invitations:[],assignments:[{id:'assn-a',title:'Fraction practice',instructions:'Ten questions',student_id:null,created_at:'2026-10-19',due_date:'2026-10-22'}],messages:[],results:[{id:'a',student_id:'student-a',assignment_id:'assn-a',released_at:'2026-10-19',score:8,max_score:10,notes:'Teacher-reviewed'},{id:'b',student_id:'student-b',assignment_id:'assn-a',released_at:'2026-10-19',score:1,max_score:10,notes:'OTHER CHILD PRIVATE'},{id:'c',student_id:'student-a',assignment_id:'assn-a',released_at:null,score:3,max_score:10,notes:'UNRELEASED PRIVATE'}]};
