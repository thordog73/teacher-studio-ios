assert.match(h,/family-announcement-form/);
assert.match(h,/family-homework-form/);
assert.match(h,/share_grades/);
assert.doesNotMatch(h,/<img src=x onerror/);
assert.match(h,/&lt;img src=x onerror=alert\(1\)&gt;/);
